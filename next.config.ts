import type { NextConfig } from "next";

/* Security headers on every page and API route.
   - frame-ancestors: other sites can't show StudentOS inside a frame (stops click-jacking).
     Only this one CSP directive is set, so YouTube, Firebase and CDN scripts keep working.
   - Permissions-Policy: camera and mic only for StudentOS itself (mock interviews), no location. */
const securityHeaders = [
  { key: "Content-Security-Policy", value: "frame-ancestors 'self'" },
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(self), microphone=(self), geolocation=(), payment=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
];

const nextConfig: NextConfig = {
  reactStrictMode: true,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
